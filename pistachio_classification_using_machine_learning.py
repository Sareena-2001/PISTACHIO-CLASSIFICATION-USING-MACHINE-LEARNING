plt.figure(figsize=(8, 6))
plt.bar(data['Class'].unique(), data['Class'].value_counts(), color=['lightgreen', 'lightblue'])
plt.xlabel('Class')
plt.ylabel('Count')
plt.title('Pistachio Class Distribution')
plt.show()