plt.figure(figsize=(6, 6))
plt.pie(data['Class'].value_counts(), labels=data['Class'].unique(), autopct='%1.1f%%', colors=['lightgreen', 'lightblue'])
plt.title('Pistachio Classification')
plt.show()

